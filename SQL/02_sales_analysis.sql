-- # Identify cities where revenue declined by more than 20% from May to June 2026.
WITH city_may_revenue AS (
    SELECT
        c.City,
        SUM(od.UnitPrice * od.Quantity) AS may_revenue
    FROM customers AS c
    INNER JOIN orders AS o
        USING (CustomerID)
    INNER JOIN order_details AS od
        USING (OrderID)
    WHERE o.OrderDate >= '2026-05-01'
      AND o.OrderDate < '2026-06-01'
    GROUP BY c.City
),
city_june_revenue AS (
    SELECT
        c.City,
        SUM(od.UnitPrice * od.Quantity) AS june_revenue
    FROM customers AS c
    INNER JOIN orders AS o
        USING (CustomerID)
    INNER JOIN order_details AS od
        USING (OrderID)
    WHERE o.OrderDate >= '2026-06-01'
      AND o.OrderDate < '2026-07-01'
    GROUP BY c.City
),
city_comparison AS (
    SELECT
        m.City,
        m.may_revenue,
        COALESCE(j.june_revenue, 0) AS june_revenue,

        COALESCE(j.june_revenue, 0) - m.may_revenue
            AS revenue_change,

        CASE
            WHEN COALESCE(j.june_revenue, 0) > m.may_revenue
                THEN 'City improved'
            WHEN COALESCE(j.june_revenue, 0) < m.may_revenue
                THEN 'City declined'
            ELSE 'No change'
        END AS performance,

        (
            COALESCE(j.june_revenue, 0) - m.may_revenue
        ) * 100.0 / m.may_revenue
            AS percentage_change
    FROM city_may_revenue AS m
    LEFT JOIN city_june_revenue AS j
        USING (City)
)
SELECT
    City,
    may_revenue,
    june_revenue,
    revenue_change,
    percentage_change
FROM city_comparison
WHERE percentage_change < -20
ORDER BY percentage_change ASC;
 