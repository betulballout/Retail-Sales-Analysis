-- # List each order with its order date, product name, and quantity sold.
SELECT o.OrderID,
       o.OrderDate,
       p.ProductNAME,
       od.Quantity
FROM orders AS o
INNER JOIN order_details AS od
USING (OrderID)
INNER JOIN products AS p
USING (ProductID);

-- # Identify the top three cities that generated the highest total revenue.
SELECT c.City,
       SUM(od.UnitPrice * Quantity) AS total_revenue
FROM customers AS c
INNER JOIN orders AS o
USING(CustomerID)
INNER JOIN order_details AS od
USING(OrderID)
GROUP BY c.City
ORDER BY total_revenue DESC
LIMIT 3;

-- # Calculate the average order revenue for each city and rank cities from highest to lowest average order revenue.
SELECT
    sub.City,
    AVG(sub.revenue) AS avg_order_revenue
FROM (
    SELECT
        c.City,
        o.OrderID,
        SUM(od.UnitPrice * od.Quantity) AS revenue
    FROM customers AS c
    INNER JOIN orders AS o
        USING (CustomerID)
    INNER JOIN order_details AS od
        USING (OrderID)
    GROUP BY c.City, o.OrderID
) AS sub
GROUP BY sub.City
ORDER BY avg_order_revenue DESC;

-- # Identify the city that generated the highest total profit.
SELECT c.City,
      SUM((od.UnitPrice - od.UnitCost)*od.Quantity) AS profit
FROM customers AS c
INNER JOIN orders As o
USING(CustomerID)
INNER JOIN order_details AS od
USING(OrderID)
GROUP BY c.City 
ORDER BY profit  DESC
LIMIT 1;


